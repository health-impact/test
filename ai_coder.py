import google.generativeai as genai
import os
import re

# 1. إعداد الاتصال بجيمني
genai.configure(api_key=os.getenv("GEMINI_API_KEY"))

# 2. اختيار الموديل المتاح تلقائياً
model_name = 'gemini-1.5-flash'
try:
    for m in genai.list_models():
        if 'generateContent' in m.supported_generation_methods:
            model_name = m.name
            break
except:
    model_name = 'models/gemini-1.5-flash'

model = genai.GenerativeModel(model_name)

# 3. قراءة ملف الموقع الحالي
with open("index.html", "r", encoding="utf-8") as f:
    current_code = f.read()

# 4. صياغة الطلب (البرومبت) بشكل صارم لمنع النصوص الزائدة
prompt = f"""
خذهذا الكود: {current_code}

المطلوب:
1. أضف أزرار مشاركة فيسبوك وواتساب وزر نسخ النصيحة لكل بطاقة نصيحة.
2. اجعل التصميم متناسقاً تماماً مع ألوان الموقع الحالية.
3. أعد لي كود HTML الكامل فقط.
4. اضافة صورة للرئيسية للموقع لها علاقة بالمحتوى.
5. اجعل مكتبة للابحاث في مجال الصحة العامة.
المطلوب في هذا التحديث:
1. إنشاء قسم "المصادر الموثوقة" يحتوي على أزرار سريعة تأخذ المستخدم إلى (PubMed, WHO Publications, CDC Infection Control).
2. إضافة جدول للأبحاث يحتوي على الأعمدة التالية: (اسم البحث، سنة النشر، المجال، رابط القراءة).
3. أضف 100 صفوف تجريبية لأبحاث حديثة اظهار خمسة ابحاث في كل مرة نضغط فيها زر عرض المزيد عن "جميع مجالات الصحة العامة".
4. تأكد من وجود زر "فلترة" بسيط للبحث داخل المكتبة.

المطلوب إصلاح أزرار "قراءة المزيد" في مكتبة الأبحاث:
1. تأكد أن كل زر "قراءة المزيد" يحتوي على رابط حقيقي (Link) لمصدر البحث.
2. استخدم روابط من موقع PubMed أو Google Scholar كمصادر افتراضية للأبحاث الحالية.
3. اجعل الرابط يفتح في "تبويب جديد" (target="_blank") لكي لا يخرج الزائر من موقعك.
4. إذا لم يتوفر رابط محدد، اجعل الزر يوجه المستخدم إلى محرك بحث PubMed مباشرة.


انشاء قسم متكامل داخل المنصة مخصص للتحقق العلمي من المعلومات والشائعات الطبية المتداولة عبر وسائل التواصل الاجتماعي والمواقع الإلكترونية. يتيح النظام للمستخدمين إرسال نصوص أو صور أو روابط لمحتوى صحي مشكوك فيه، ليتم تحليله وتصنيفه وفق معايير علمية واضحة إلى: صحيح، مضلل، أو خاطئ. يتضمن كل تحليل شرحًا مبسطًا مدعومًا بمراجع ودراسات ومصادر طبية موثوقة، مع بيان مستوى الخطورة المحتمل للمعلومة الخاطئة. يهدف هذا القسم إلى تعزيز الوعي الصحي، مكافحة التضليل الطبي، وبناء قاعدة بيانات عربية موثوقة للشائعات الصحية الشائعة.
تطوير مكتبة الأبحاث بمحرك بحث ذكي
تطوير مكتبة الأبحاث الحالية عبر إنشاء نظام بحث ذكي ومتقدم يسمح للمستخدم بالوصول السريع والدقيق إلى الدراسات والمقالات العلمية. يعتمد النظام على تصنيف الأبحاث حسب التخصص، الكلمات المفتاحية، سنة النشر، نوع الدراسة، والموضوع الصحي، مع إمكانية البحث باللغة العربية والإنجليزية. كما يتضمن اقتراحات ذكية مرتبطة بموضوع البحث وعرض ملخصات مبسطة للأبحاث لتسهيل فهم المحتوى العلمي لغير المختصين. يهدف هذا التطوير إلى تعزيز تجربة المستخدم وتحويل المكتبة إلى مرجع علمي منظم وسهل الاستخدام للباحثين والمهتمين بالصحة العامة.
انشاء نظام حسابات شخصية متكامل داخل المنصة يتيح للمستخدم إنشاء ملف شخصي خاص به للوصول إلى تجربة استخدام أكثر تنظيمًا وتفاعلية. يوفّر النظام إمكانية حفظ المقالات والنصائح الصحية والأبحاث المفضلة للرجوع إليها لاحقًا، بالإضافة إلى إنشاء قوائم مخصصة وتنظيم المحتوى حسب اهتمامات المستخدم. كما يتضمن النظام سجلًا للنشاطات الأخيرة، وإشعارات بالمحتوى الجديد المرتبط باهتمامات المستخدم، واقتراحات ذكية مبنية على تفاعله داخل المنصة و تلقي تنبيهات عند إضافة أبحاث أو تحديثات جديدة.


المطلوب تحويل قسم "فحص الشائعات" إلى نظام ذكاء اصطناعي حقيقي:
1. استخدم JavaScript لإنشاء اتصال مع API الخاص بـ Gemini داخل المتصفح.
2. عندما يكتب المستخدم "إشاعة"، يجب أن تظهر رسالة "جاري الفحص عبر المصادر المعتمدة (WHO, CDC, PubMed)...".
3. صغ "البرومبت الداخلي" للنظام بحيث يحلل الإشاعة ويرد بناءً على الأدلة العلمية فقط، مع ذكر المصدر في نهاية الإجابة.
4. أضف تأثيرات بصرية (Animations) توحي بأن الذكاء الاصطناعي يقوم بالتفكير والبحث الآن.
5. تأكد من أن مفتاح الـ API يتم استدعاؤه بشكل آمن من إعدادات الموقع.

المشكلة: يظهر خطأ "لم يتم تهيئة نموذج Gemini" عند الضغط على التحقق.
المطلوب الحل التالي:
1. بدلاً من الاتصال المباشر بـ API من المتصفح، قم ببناء "قاعدة بيانات ذكية" (JavaScript Object) داخل الكود.
2. اطلب من Gemini (أنت) توليد قائمة بـ 30 إشاعة طبية شائعة في ليبيا والعالم العربي وإجاباتها الموثوقة (مثل: البنادول والقهوة، الفيب، المضادات الحيوية، الثوم والضغط، إلخ).
3. برمج محرك بحث ذكي (Fuzzy Search) داخل الموقع يبحث في هذه القائمة ويعطي الإجابة فوراً بأسلوب "الذكاء الاصطناعي".
4. إذا لم يجد النظام الإجابة، اجعله يظهر رسالة احترافية: "هذه المعلومة تخضع حالياً للمراجعة المخبرية، سيتم تحديثها في التقرير القادم".
5. أضف زر "اطلب فحص إشاعة جديدة" يفتح واتساب للتواصل معك مباشرة (دكتور متخصص).

أعد لي كود HTML الكامل والنظيف فقط.
أعد لي كود HTML الكامل فقط.

أعد لي كود HTML الكامل فقط بدون أي شرح.
مهم جداً وقواعد صارمة:
- ممنوع كتابة أي كلمة خارج كود الـ HTML.
- ابدأ مباشرة بـ <!DOCTYPE html>.
- لا تكتب "إليك الكود" أو "بالتأكيد" أو أي شرح.
- لا تستخدم علامات الماركدوان مثل ```html.
"""

# 5. طلب الكود وتنظيفه
try:
    response = model.generate_content(prompt)
    raw_text = response.text
    
    # محاولة استخراج الكود فقط بين وسوم html لضمان النظافة
    match = re.search(r'<!DOCTYPE html>.*</html>', raw_text, re.DOTALL | re.IGNORECASE)
    if match:
        clean_code = match.group(0)
    else:
        # إذا لم يجد الوسوم، يقوم بإزالة علامات الماركدوان التقليدية
        clean_code = re.sub(r'```html\n|```', '', raw_text)

    # 6. حفظ الكود النظيف في الملف
    with open("index.html", "w", encoding="utf-8") as f:
        f.write(clean_code.strip())
    print(f"تم التحديث بنجاح باستخدام موديل: {model_name}")

except Exception as e:
    print(f"حدث خطأ أثناء التحديث: {e}")
