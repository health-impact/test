import google.generativeai as genai
import os
import re
import json 
import time 
 
# 1. إعداد الاتصال بجيمني واختيار الموديل المتاح تلقائياً
genai.configure(api_key=os.getenv("GEMINI_API_KEY"))

model_name = 'gemini-1.5-flash'
try:
    for m in genai.list_models():
        if 'generateContent' in m.supported_generation_methods:
            model_name = m.name
            break
except: 
    model_name = 'models/gemini-1.5-flash'

model = genai.GenerativeModel(model_name)

# 2. قراءة ملف الموقع الحالي
try:
    with open("index.html", "r", encoding="utf-8") as f:
        current_code = f.read()
except FileNotFoundError:
    print("خطأ: لم يتم العثور على ملف index.html في المسار الحالي.")
    exit(1)

# 3. البرومبت المطور والمطهر تماماً من المفضلة مع شروط الأخبار الجديدة
prompt = """
خذ كود الـ HTML الحالي للموقع:
{{CURRENT_HTML_CODE}}

المطلوب منك هو تحديث هذا الكود وإعادة صياغته بالكامل لينفذ المهام التالية بدقة عالية:

أولاً: تحديثات وتطويرات بنية الموقع الأساسية:
 أنت مهندس واجهات خبير ومبرمج حذر. المطلوب منك هو إجراء تحديثات على كود الـ HTML الحالي للموقع مع الالتزام الصارم والمقدس بعدم تغيير الهيكل البصري، أو ألوان الـ CSS، أو الخطوط، أو تصميم الأقسام الحالية. حافظ على روح التصميم الحالي 100% ونفذ الآتي بدقة:

أولاً: إضافة قسم "تواصل معنا" (Contact Us):
- قم بإنشاء قسم أنيق ومتناسق تماماً مع ألوان الموقع الحالية (الأخضر الطبي والأزرق الداكن) وضعه في نهاية الصفحة (مباشرة قبل الفوتر Footer).
- يحتوي القسم على واجهة نموذج تواصل (الاسم، البريد الإلكتروني، نص الرسالة) مع زر إرسال متناسق.
- أضف بجانبه معلومات التواصل الأساسية المذكورة في موقعك (مثل البريد الإلكتروني الرسمي، وأزرار التواصل السريع عبر الواتساب والفيسبوك).

ثانياً: إرجاع التاريخ لقسم "التوعية الذكية":
- في قسم التوعية الذكية (وليس قسم آخر الأخبار)، قم بإعادة إظهار وتفعيل حقل التاريخ في كروت النصائح الطبية والتوعوية لكي يرى المستخدم تاريخ نشر النصيحة الطبية بشكل واضح ومنظم (مثال بصيغة: DD-MM-YYYY أو بالدستور المحلي).

ثالثاً: صورة حية ومميزة للرئيسية (Hero Image):
- ابحث عن وسم الصورة الأساسية في قسم الرئيسية (Hero Section) واستبدله برابط صورة عالية الدقة، حقيقية ومعبرة جداً عن الصحة العامة والمختبرات الميكروبية ومكافحة العدوى من Unsplash (مثل: صورة مجهر متطور في مختبر نظيف، أو فني مختبر يحلل عينات بكتيرية)، وتأكد من ضبط أبعادها (Object-fit: cover) لكي لا تخرب التناسق.

رابعاً: ضبط صور الأخبار في مصفوفة الجافاسكريبت:
- تأكد أن قسم "آخر الأخبار" (الذي يقع بعد من نحن) يعرض الأخبار الحية بمصفوفتها الذكية. 
- أمر صارم: يجب أن تكون الصورة المربوطة بكل خبر داخل المصفوفة هي صورة حقيقية ودلالية تعبر عن تفاصيل الخبر نفسه (كأنها الصورة الأصلية الملتقطة مع الخبر في مصدره الموثوق)، ويُمنع منعاً باتاً تنزيل أو عرض أي خبر بصورة مكسورة أو فارغة.

خامساً: تطوير وتعميق بيانات قسم "من نحن":
- ابحث عن نصوص قسم "من نحن" الحالي، وقم بإعادة صياغتها وتطويرها لتصبح أكثر احترافية وعمقاً من الناحية العلمية والأكاديمية (يركز على نشر الوعي بالصحة العامة، مكافحة العدوى، سلامة الأغذية، ومقاومة البكتيريا للمضادات الحيوية، ودور الفحوصات المختبرية الدقيقة).
- تحذير: قم بتطوير الكلمات والنصوص فقط، ويُمنع منعاً باتاً تعديل الـ Classes أو الـ Divs أو توزيع الألوان الخاصة بهذا القسم في الـ HTML.

شروط الاستجابة الصارمة:
- ابدأ الرد مباشرة بـ <!DOCTYPE html> وانته بـ </html>.
- ممنوع كتابة أي شروحات أو مقدمات خارج كود الـ HTML لتفادي أخطاء التشغيل في الـ Actions.

شروط صارمة للاستجابة:
- ممنوع كتابة أي كلمة شرح أو تمهيد خارج كود الـ HTML.
- ابدأ الرد مباشرة بـ <!DOCTYPE html> وانته بـ </html> دون استخدام علامات الماركدوان الزائدة.
-ازلة  نوع الدراسة نهائيا من الفلترة والاعمدة في مكتبة الابحاث
- يُمنع منعاً باتاً تنزيل أو عرض أي خبر بدون صورة، ويُمنع ترك حقل الصورة فارغاً. يجب تزويد كل خبر برابط صورة عالية الجودة ومباشرة من مصدر الخبر
"""

# حقن الكود بأمان بدون f-string لمنع أخطاء التداخل مع بايثون
final_prompt = prompt.replace("{{CURRENT_HTML_CODE}}", current_code)

print("جاري تشغيل السكربت المطور لتحديث قسم الأخبار وحذف التواريخ والمفضلة... ⏳")

# 4. تنفيذ الطلب وحفظ الملف
try:
    response = model.generate_content(final_prompt)
    raw_text = response.text
    
    match = re.search(r'<!DOCTYPE html>.*</html>', raw_text, re.DOTALL | re.IGNORECASE)
    if match:
        clean_code = match.group(0)
    else:
        clean_code = re.sub(r'```html\n|```', '', raw_text)

    with open("index.html", "w", encoding="utf-8") as f:
        f.write(clean_code.strip())
        
    print("تم التحديث بنجاح تام! 🚀 الأخبار الآن بعد (من نحن) بدون تواريخ وبصور دلالية ممتازة.")
    print(f"الموديل المستخدم: {model_name}")

except Exception as e:
    print(f"حدث خطأ أثناء معالجة التحديث: {e}")
